export type Labels = typeof LABELS.en;

interface DashLangContextValue {
  lang: DashLang;
  setLang: (l: DashLang) => void;
  labels: Labels;
  isRTL: boolean;
}

import React from 'react';

const DashLangContext = createContext<DashLangContextValue>({
  lang: 'en',
  setLang: () => {},
  labels: LABELS.en,
  isRTL: false,
});

// localStorage-backed external store — avoids setState-in-effect and stays
// hydration-safe (server snapshot is always 'en', client re-syncs on mount).
let langListeners: Array<() => void> = [];

function subscribeLang(listener: () => void) {
  langListeners.push(listener);
  return () => {
    langListeners = langListeners.filter((l) => l !== listener);
  };
}

function getLangSnapshot(): DashLang {
  try {
    const stored = localStorage.getItem('dash-lang');
    if (stored === 'en' || stored === 'ar' || stored === 'tr') return stored;
  } catch {}
  return 'en';
}

export function DashLangProvider({ children }: { children: ReactNode }) {
  const lang = useSyncExternalStore(subscribeLang, getLangSnapshot, () => 'en' as DashLang);

  function setLang(l: DashLang) {
    try { localStorage.setItem('dash-lang', l); } catch {}
    langListeners.forEach((listener) => listener());
  }

  return React.createElement(
    DashLangContext.Provider,
    { value: { lang, setLang, labels: LABELS[lang] as Labels, isRTL: lang === 'ar' } },
    children,
  );
}

export function useDashLang() {
  return useContext(DashLangContext);
}
